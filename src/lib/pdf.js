/**
 * SakhiNidhi PDF Report Engine (jsPDF + autotable)
 * Generates Member Passbook, Group Cash Book, Loan Register, and Attendance Register.
 */

import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

function addHeader(doc, title, groupName, village, dateRange = '') {
  doc.setFillColor(27, 107, 74); // Deep green #1B6B4A
  doc.rect(0, 0, 210, 28, 'F');

  doc.setTextColor(255, 249, 240); // Cream #FFF9F0
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('SakhiNidhi - SHG Micro-Accounting', 14, 12);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text(`${groupName || 'Sakhi Mandal'} (${village || 'Jharkhand'})`, 14, 20);

  doc.setTextColor(27, 107, 74);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text(title, 14, 38);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  const dateStr = dateRange || `Date: ${new Date().toLocaleDateString('en-IN')}`;
  doc.text(dateStr, 14, 44);
}

function addFooter(doc) {
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      'Generated by SakhiNidhi | Offline-First SHG Micro-Accounting (Tribe 2026)',
      14,
      290
    );
    doc.text(`Page ${i} of ${pageCount}`, 190, 290, { align: 'right' });
  }
}

/**
 * 1. Member Individual Passbook PDF
 */
export function generateMemberPassbookPdf({ group, member, savings = [], repayments = [] }) {
  const doc = new jsPDF();
  addHeader(
    doc,
    `Member Passbook: ${member?.name || 'Member'} (${member?.phone || 'No phone'})`,
    group?.name,
    group?.village
  );

  const tableData = [];
  let cumulativeSavings = 0;

  savings.forEach((s) => {
    cumulativeSavings += Number(s.amount) || 0;
    tableData.push([
      s.date || 'Weekly',
      'Weekly Saving',
      `+ ₹${s.amount}`,
      '-',
      `₹${cumulativeSavings}`
    ]);
  });

  repayments.forEach((r) => {
    tableData.push([
      r.date || '-',
      'Loan Repayment',
      `-`,
      `₹${r.amount} (P: ₹${r.principalPaid}, I: ₹${r.interestPaid})`,
      `₹${cumulativeSavings}`
    ]);
  });

  autoTable(doc, {
    startY: 50,
    head: [['Date', 'Transaction', 'Savings (In)', 'Loan Repayment', 'Total Savings Balance']],
    body: tableData.length > 0 ? tableData : [['-', 'No transactions recorded', '-', '-', '-']],
    theme: 'striped',
    headStyles: { fillColor: [27, 107, 74], textColor: 255 },
    styles: { fontSize: 9 }
  });

  addFooter(doc);
  doc.save(`Passbook_${member?.name?.replace(/\s+/g, '_') || 'Member'}.pdf`);
  return doc;
}

/**
 * 2. Group Cash Book PDF
 */
export function generateCashBookPdf({ group, savings = [], repayments = [], loans = [], summary = {} }) {
  const doc = new jsPDF();
  addHeader(doc, 'Group Cash Book (Jama-Kharcha)', group?.name, group?.village);

  // Summary box
  doc.setFillColor(255, 249, 240);
  doc.roundedRect(14, 50, 182, 22, 3, 3, 'F');
  doc.setFontSize(10);
  doc.setTextColor(27, 107, 74);
  doc.setFont('helvetica', 'bold');
  doc.text(`Total Cash in Fund: ₹${summary.fundBalance || 0}`, 20, 58);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  doc.text(`Total Savings: ₹${summary.totalSavings || 0}  |  Interest Earned: ₹${summary.totalInterest || 0}  |  Loans Out: ₹${summary.loansOutstanding || 0}`, 20, 66);

  const tableRows = [];

  // Inflows
  savings.forEach(s => {
    tableRows.push([s.date || '-', 'Saving Deposit', `+ ₹${s.amount}`, '-', s.reversed ? 'Reversed' : 'Credited']);
  });
  repayments.forEach(r => {
    tableRows.push([r.date || '-', `Loan Repayment (P: ${r.principalPaid}, I: ${r.interestPaid})`, `+ ₹${r.amount}`, '-', 'Credited']);
  });

  // Outflows
  loans.forEach(l => {
    tableRows.push([l.issuedDate || '-', `Loan Disbursed (${l.purpose || 'General'})`, '-', `- ₹${l.principal}`, l.status]);
  });

  autoTable(doc, {
    startY: 78,
    head: [['Date', 'Particulars / Description', 'Receipt (Jama)', 'Payment (Kharcha)', 'Status']],
    body: tableRows.length > 0 ? tableRows : [['-', 'No ledger entries', '-', '-', '-']],
    theme: 'grid',
    headStyles: { fillColor: [27, 107, 74], textColor: 255 },
    styles: { fontSize: 8 }
  });

  addFooter(doc);
  doc.save(`CashBook_${group?.name?.replace(/\s+/g, '_') || 'Group'}.pdf`);
  return doc;
}

/**
 * 3. Loan Register PDF
 */
export function generateLoanRegisterPdf({ group, loans = [], members = [] }) {
  const doc = new jsPDF();
  addHeader(doc, 'Loan Disbursal & Outstanding Register', group?.name, group?.village);

  const memberMap = {};
  members.forEach(m => { memberMap[m.id] = m.name; });

  const rows = loans.map((l, index) => [
    index + 1,
    memberMap[l.memberId] || `Member #${l.memberId}`,
    `₹${l.principal}`,
    `${l.interestRate || 2}%`,
    `${l.tenureMonths || 5} mos`,
    l.purpose || 'Need',
    l.issuedDate || '-',
    l.status.toUpperCase()
  ]);

  autoTable(doc, {
    startY: 50,
    head: [['#', 'Borrower Name', 'Principal', 'Interest Rate', 'Tenure', 'Purpose', 'Issued Date', 'Status']],
    body: rows.length > 0 ? rows : [['-', '-', '-', '-', '-', '-', '-', '-']],
    theme: 'striped',
    headStyles: { fillColor: [27, 107, 74], textColor: 255 },
    styles: { fontSize: 8.5 }
  });

  addFooter(doc);
  doc.save(`LoanRegister_${group?.name?.replace(/\s+/g, '_') || 'Group'}.pdf`);
  return doc;
}

/**
 * 4. Attendance Register PDF
 */
export function generateAttendanceRegisterPdf({ group, members = [], meetings = [], attendance = [] }) {
  const doc = new jsPDF('landscape');
  doc.setFillColor(27, 107, 74);
  doc.rect(0, 0, 297, 26, 'F');
  doc.setTextColor(255, 249, 240);
  doc.setFontSize(15);
  doc.setFont('helvetica', 'bold');
  doc.text('SakhiNidhi - SHG Attendance Register (Upasthiti Panjika)', 14, 12);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`${group?.name || 'Sakhi Mandal'} (${group?.village || 'Jharkhand'})`, 14, 20);

  // Build matrix
  const sortedMeetings = [...meetings].sort((a, b) => new Date(a.meetingDate) - new Date(b.meetingDate)).slice(-10);
  const head = ['#', 'Member Name', ...sortedMeetings.map(m => m.meetingDate || `M#${m.meetingNumber}`)];

  const attMap = {};
  attendance.forEach(a => {
    attMap[`${a.meetingId}_${a.memberId}`] = a.status === 'present' ? 'P' : 'A';
  });

  const body = members.map((m, idx) => {
    const row = [idx + 1, m.name];
    sortedMeetings.forEach(meet => {
      row.push(attMap[`${meet.id}_${m.id}`] || 'P');
    });
    return row;
  });

  autoTable(doc, {
    startY: 35,
    head: [head],
    body,
    theme: 'grid',
    headStyles: { fillColor: [27, 107, 74], textColor: 255 },
    styles: { fontSize: 8, halign: 'center' },
    columnStyles: { 1: { halign: 'left' } }
  });

  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text('Generated by SakhiNidhi | Offline-First SHG Micro-Accounting', 14, 200);
  }

  doc.save(`Attendance_${group?.name?.replace(/\s+/g, '_') || 'Group'}.pdf`);
  return doc;
}

