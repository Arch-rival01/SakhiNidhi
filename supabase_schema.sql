-- SakhiNidhi (सखीनिधि) Supabase Cloud Schema
-- Run this in your Supabase SQL Editor to set up cloud synchronization

-- 1. GROUPS TABLE
CREATE TABLE IF NOT EXISTS public.groups (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    village TEXT,
    meeting_day TEXT,
    weekly_saving NUMERIC DEFAULT 100,
    interest_rate NUMERIC DEFAULT 2,
    late_fine NUMERIC DEFAULT 10,
    max_loan_multiple INT DEFAULT 3,
    pin TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. MEMBERS TABLE
CREATE TABLE IF NOT EXISTS public.members (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    group_id BIGINT REFERENCES public.groups(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    phone TEXT,
    role TEXT DEFAULT 'member',
    avatar_color TEXT,
    active BOOLEAN DEFAULT TRUE,
    joined_date TIMESTAMPTZ DEFAULT NOW(),
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. MEETINGS TABLE
CREATE TABLE IF NOT EXISTS public.meetings (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    group_id BIGINT REFERENCES public.groups(id) ON DELETE CASCADE,
    meeting_number INT,
    meeting_date DATE NOT NULL,
    is_locked BOOLEAN DEFAULT FALSE,
    locked_at TIMESTAMPTZ,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. ATTENDANCE TABLE
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    meeting_id BIGINT REFERENCES public.meetings(id) ON DELETE CASCADE,
    member_id BIGINT REFERENCES public.members(id) ON DELETE CASCADE,
    status TEXT NOT NULL, -- 'present' | 'absent'
    date DATE,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. SAVINGS TABLE
CREATE TABLE IF NOT EXISTS public.savings (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    meeting_id BIGINT REFERENCES public.meetings(id) ON DELETE CASCADE,
    member_id BIGINT REFERENCES public.members(id) ON DELETE CASCADE,
    amount NUMERIC NOT NULL,
    date DATE NOT NULL,
    reversed BOOLEAN DEFAULT FALSE,
    reversal_reason TEXT,
    reversed_at TIMESTAMPTZ,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. LOANS TABLE
CREATE TABLE IF NOT EXISTS public.loans (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    group_id BIGINT REFERENCES public.groups(id) ON DELETE CASCADE,
    member_id BIGINT REFERENCES public.members(id) ON DELETE CASCADE,
    principal NUMERIC NOT NULL,
    purpose TEXT,
    interest_rate NUMERIC DEFAULT 2,
    tenure_months INT DEFAULT 4,
    status TEXT DEFAULT 'active', -- 'active' | 'paid' | 'overdue'
    disbursed_date DATE NOT NULL,
    due_date DATE,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. REPAYMENTS TABLE
CREATE TABLE IF NOT EXISTS public.repayments (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    loan_id BIGINT REFERENCES public.loans(id) ON DELETE CASCADE,
    member_id BIGINT REFERENCES public.members(id) ON DELETE CASCADE,
    meeting_id BIGINT REFERENCES public.meetings(id) ON DELETE CASCADE,
    amount NUMERIC NOT NULL,
    principal_paid NUMERIC DEFAULT 0,
    interest_paid NUMERIC DEFAULT 0,
    fine_paid NUMERIC DEFAULT 0,
    date DATE NOT NULL,
    reversed BOOLEAN DEFAULT FALSE,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. AUDIT LOG TABLE
CREATE TABLE IF NOT EXISTS public.audit_log (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    group_id BIGINT,
    action TEXT NOT NULL,
    entity TEXT NOT NULL,
    entity_id BIGINT,
    details TEXT,
    actor TEXT,
    timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS) but allow anonymous access with API key for SHG sync
ALTER TABLE public.groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.meetings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.savings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.repayments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;

-- Allow anon public operations (Read, Insert, Update) via API key
CREATE POLICY "Allow public read-write for groups" ON public.groups FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write for members" ON public.members FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write for meetings" ON public.meetings FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write for attendance" ON public.attendance FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write for savings" ON public.savings FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write for loans" ON public.loans FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write for repayments" ON public.repayments FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read-write for audit_log" ON public.audit_log FOR ALL USING (true) WITH CHECK (true);

